"""Explicit maintainer step; normal Rust builds use committed data, without Python.

Hajdu source: the Glassure CSV data. Xraylib source: the vendored 4.2.1
FF.dat/SF.dat tables; only lossless decimal-to-f64 and binary packing are done.
"""
import csv
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CORE = ROOT / "rust/glassure-core"


def main():
    source = ROOT / "glassure/data/hajdu"
    def rows(name):
        with (source / name).open() as stream:
            return sorted(csv.DictReader(stream), key=lambda r: r["Element"])
    text = '// Generated by rust/scripts/generate_tables.py from Glassure Hajdu CSV tables.\n'
    text += '#![allow(clippy::approx_constant)] // Preserve exact tabulated coefficients.\nuse super::CoherentRow;\n'
    text += '#[rustfmt::skip]\npub(super) static HAJDU_COHERENT: &[CoherentRow] = &[\n'
    for row in rows("param_coherent_scattering_factors.csv"):
        a = [float(row[f"A{i}"]) for i in range(1, 5)]
        b = [float(row[f"B{i}"]) for i in range(1, 5)]
        text += f'CoherentRow {{ key: "{row["Element"]}", a: {a!r}, b: {b!r}, c: {float(row["C"])!r} }},\n'
    text += '];\n#[rustfmt::skip]\npub(super) static HAJDU_INCOHERENT: &[(&str, [f64; 4])] = &[\n'
    for row in rows("param_incoherent_scattering_intensities.csv"):
        text += f'("{row["Element"]}", {[float(row[k]) for k in ("Z", "M", "K", "L")]!r}),\n'
    text += '];\n'
    for path in sorted(source.glob("*.csv")):
        text += f'// {path.name} SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}\n'
    (CORE / "src/hajdu_data.rs").write_text(text)
    provenance = {"version": "xraylib-4.2.1", "source": "https://github.com/tschoonj/xraylib/tree/xraylib-4.2.1", "tables": {}}
    for name in ("FF", "SF"):
        path = CORE / "data/xraylib" / (name + ".dat")
        words = iter(path.read_text().split()); tables = []
        while True:
            try:
                count = int(next(words))
            except StopIteration:
                break
            tables.append([[float(next(words)) for _ in range(3)] for _ in range(count)])
        binary = b"GLXR0001" + struct.pack("<I", len(tables))
        for rows_ in tables:
            binary += struct.pack("<I", len(rows_))
            binary += b"".join(struct.pack("<ddd", *row) for row in rows_)
        path.with_suffix(".bin").write_bytes(binary)
        provenance["tables"][name] = {"elements": len(tables), "text_sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                                     "binary_sha256": hashlib.sha256(binary).hexdigest()}
    (CORE / "data/xraylib/provenance.json").write_text(json.dumps(provenance, indent=2) + "\n")


if __name__ == "__main__":
    main()
